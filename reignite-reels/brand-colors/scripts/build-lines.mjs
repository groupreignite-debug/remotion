// Build src/data/lines.json (per-line start/end) from src/data/words.json (Scribe word timings on the
// edited vo.mp3) by aligning the transcribed words to the script lines.
// Usage: node scripts/build-lines.mjs <gap1Sec> <gap2Sec>
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const [g1, g2] = process.argv.slice(2).map(Number);
const words = JSON.parse(readFileSync("src/data/words.json", "utf8")).filter((w) => w.text.trim());

// Pull the script text out of script.ts so there's one source of truth.
const src = readFileSync("src/data/script.ts", "utf8");
const SCRIPT = [...src.matchAll(/"(\d\d)": "((?:[^"\\]|\\.)*)"/g)].map((m) => ({ id: m[1], text: m[2].replace(/\\"/g, '"') }));

const norm = (s) =>
  s
    .replace(/[ً-ْـ]/g, "") // harakat, shadda, tatweel
    .replace(/[إأآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[^\p{L}\p{N}]/gu, "")
    .toLowerCase();

const tokens = SCRIPT.flatMap((l) => l.text.split(/\s+/).map((t) => ({ id: l.id, t: norm(t) })).filter((x) => x.t));
const ws = words.map((w) => ({ ...w, t: norm(w.text) }));

// Character-bigram similarity.
const sim = (a, b) => {
  if (!a || !b) return 0;
  if (a === b) return 1;
  const bg = (s) => new Set([...Array(Math.max(1, s.length - 1))].map((_, i) => s.slice(i, i + 2)));
  const A = bg(a);
  const B = bg(b);
  let n = 0;
  A.forEach((x) => B.has(x) && n++);
  return (2 * n) / (A.size + B.size);
};

// Needleman-Wunsch alignment: words (i) vs script tokens (j).
const I = ws.length;
const J = tokens.length;
const GAPP = -0.4;
const S = Array.from({ length: I + 1 }, () => new Float64Array(J + 1));
const P = Array.from({ length: I + 1 }, () => new Uint8Array(J + 1));
for (let i = 1; i <= I; i++) (S[i][0] = i * GAPP), (P[i][0] = 1);
for (let j = 1; j <= J; j++) (S[0][j] = j * GAPP), (P[0][j] = 2);
for (let i = 1; i <= I; i++)
  for (let j = 1; j <= J; j++) {
    const d = S[i - 1][j - 1] + (sim(ws[i - 1].t, tokens[j - 1].t) * 2 - 0.6);
    const u = S[i - 1][j] + GAPP;
    const l = S[i][j - 1] + GAPP;
    if (d >= u && d >= l) (S[i][j] = d), (P[i][j] = 0);
    else if (u >= l) (S[i][j] = u), (P[i][j] = 1);
    else (S[i][j] = l), (P[i][j] = 2);
  }
const lineOf = new Array(I).fill(null);
for (let i = I, j = J; i > 0 || j > 0; ) {
  const p = P[i][j];
  if (i > 0 && j > 0 && p === 0) (lineOf[i - 1] = tokens[j - 1].id), i--, j--;
  else if (i > 0 && (j === 0 || p === 1)) i--;
  else j--;
}
// Unaligned words inherit the previous word's line.
for (let i = 0; i < I; i++) if (!lineOf[i]) lineOf[i] = lineOf[i - 1] ?? "01";

const lines = SCRIPT.map(({ id }) => {
  const mine = ws.filter((_, i) => lineOf[i] === id);
  if (!mine.length) throw new Error(`No words aligned to line ${id}`);
  return { id, start: +mine[0].start.toFixed(3), end: +mine[mine.length - 1].end.toFixed(3) };
});

const FFPROBE = process.platform === "win32" ? "node_modules/@remotion/compositor-win32-x64-msvc/ffprobe.exe" : "ffprobe";
const probe = execFileSync(FFPROBE, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", "public/audio/vo.mp3"]).toString();
const voEnd = +Number(probe).toFixed(3);

writeFileSync("src/data/lines.json", JSON.stringify({ _note: "Generated by scripts/build-lines.mjs from words.json", voEnd, gaps: [g1, g2], lines }, null, 2) + "\n");
console.table(lines);
console.log({ voEnd, gaps: [g1, g2] });
